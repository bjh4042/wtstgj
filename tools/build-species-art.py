#!/usr/bin/env python3
"""Rebuild dist/species-art.mjs from the immutable generated sprite sheets."""

from pathlib import Path
from PIL import Image
import numpy as np
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "dist" / "assets" / "species"
OUT = ROOT / "dist" / "species-art.mjs"
GROUPS = [
    (1, 20, [5, 5, 5, 5]),
    (21, 40, [5, 5, 6, 6]),  # first 20 map to IDs 21–40; final two are unused
    (41, 60, [5, 5, 5, 5]),
    (61, 80, [5, 5, 5, 5]),
    (81, 100, [5, 5, 5, 5]),
    (101, 120, [5, 5, 5, 5]),
    (121, 140, [5, 5, 5, 5]),
    (141, 151, [5, 5, 1]),
]


def components(path, rows):
    image = Image.open(path)
    if image.mode != "RGBA" or image.getextrema()[3] != (0, 255):
        raise RuntimeError(f"{path.name}: genuine RGBA transparency required")
    labels, _ = ndimage.label(np.asarray(image.getchannel("A")) > 16)
    boxes = []
    for label, obj in enumerate(ndimage.find_objects(labels), 1):
        if obj is None or int((labels[obj] == label).sum()) < 2000:
            continue
        ys, xs = obj
        boxes.append([xs.start, ys.start, xs.stop - xs.start, ys.stop - ys.start])
    if len(boxes) != sum(rows):
        raise RuntimeError(f"{path.name}: expected {sum(rows)} sprites, found {len(boxes)}")
    boxes.sort(key=lambda box: box[1] + box[3] / 2)
    ordered, offset = [], 0
    for row_size in rows:
        row = boxes[offset:offset + row_size]
        row.sort(key=lambda box: box[0] + box[2] / 2)
        ordered.extend(row)
        offset += row_size
    padded = []
    for x, y, width, height in ordered:
        x0, y0 = max(0, x - 4), max(0, y - 4)
        x1, y1 = min(image.width, x + width + 4), min(image.height, y + height + 4)
        padded.append([x0, y0, x1 - x0, y1 - y0])
    return image.width, image.height, padded


def build():
    manifest = {species_id: {} for species_id in range(1, 152)}
    for side in ("front", "back"):
        for first, last, rows in GROUPS:
            path = ASSETS / f"species-{side}-{first:03d}-{last:03d}.png"
            width, height, boxes = components(path, rows)
            for index, species_id in enumerate(range(first, last + 1)):
                manifest[species_id][side] = (f"assets/species/{path.name}", width, height, boxes[index])

    lines = ["// Generated by tools/build-species-art.py. Species IDs are immutable.",
             "export const SPECIES_ART_BY_ID=Object.freeze({"]
    for species_id, sides in manifest.items():
        entries = []
        for side in ("front", "back"):
            src, width, height, box = sides[side]
            entries.append(f"{side}:Object.freeze({{src:'{src}',width:{width},height:{height},source:Object.freeze({box})}})")
        lines.append(f" {species_id}:Object.freeze({{{','.join(entries)}}}),")
    lines += [
        "});", "",
        "function speciesId(value){",
        " if(typeof value==='number'&&Number.isInteger(value))return value;",
        " if(value&&typeof value==='object'){const id=Number(value.id??value.no);return Number.isInteger(id)?id:null}",
        " return null;", "}", "",
        "export function speciesArt(monOrId,side='front'){",
        " const id=speciesId(monOrId),facing=side==='back'?'back':'front';",
        " if(id===null||id<1||id>151)return null;",
        " const art=SPECIES_ART_BY_ID[id]?.[facing];return art?{id,side:facing,...art}:null;", "}", "",
        "export function speciesArtMarkup(monOrId,w,side='front'){",
        " const art=speciesArt(monOrId,side);if(!art)return null;",
        " const [sx,sy,sw,sh]=art.source,size=Number(w);",
        " const width=Number.isFinite(size)&&size>0?`width:${size}px;`:'';",
        " return `<span class=\"species-art species-art-${art.side}\" data-species-art=\"${art.id}\" aria-hidden=\"true\" style=\"${width}aspect-ratio:${sw}/${sh};position:relative;display:inline-block;overflow:hidden\"><img src=\"${art.src}\" alt=\"\" draggable=\"false\" style=\"position:absolute;max-width:none;width:${art.width/sw*100}%;height:${art.height/sh*100}%;left:${-sx/sw*100}%;top:${-sy/sh*100}%;image-rendering:pixelated\"></span>`;", "}", "",
        "const imageCache=new Map();",
        "export function drawSpecies(ctx,monOrId,x,y,options={}){",
        " const art=speciesArt(monOrId,options.side??'front');if(!art)return null;",
        " if(typeof Image==='undefined')return false;",
        " let image=imageCache.get(art.src);",
        " if(!image){image=new Image();image.decoding='async';image.src=art.src;imageCache.set(art.src,image)}",
        " if(!image.complete||!image.naturalWidth)return false;",
        " const [sx,sy,sw,sh]=art.source,width=Number(options.width)>0?Number(options.width):48,height=width*sh/sw;",
        " const smoothing=ctx.imageSmoothingEnabled;ctx.imageSmoothingEnabled=false;",
        " ctx.drawImage(image,sx,sy,sw,sh,x-width/2,y-height,width,height);ctx.imageSmoothingEnabled=smoothing;",
        " return true;", "}", "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    build()
